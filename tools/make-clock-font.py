#!/usr/bin/env python3
"""Make the oven clock's digit bitmaps (0-9 and ':') from a TTF as a C header.
Usage: make-clock-font.py <font.ttf> <out.h> [preview.png]"""
import sys
from PIL import Image, ImageDraw, ImageFont
path, outpath = sys.argv[1], sys.argv[2]
chars = '0123456789:'
def widest(f):
    return max(f.getlength(f'{h}:{m:02d}') for h in range(1, 13) for m in range(60))
size = 100
while True:
    f = ImageFont.truetype(path, size + 2); bb = f.getbbox('0123456789')
    if widest(f) > 756 or bb[3] - bb[1] > 370: break
    size += 2
f = ImageFont.truetype(path, size); bb = f.getbbox('0123456789'); top, H = bb[1], bb[3] - bb[1]
print('size', size, 'digit height', H, 'widest', round(widest(f)))
data, glyphs = [], []
for c in chars:
    l, _, r, _ = f.getbbox(c); w = max(1, r - l); adv = round(f.getlength(c))
    im = Image.new('L', (w, H), 0); ImageDraw.Draw(im).text((-l, -top), c, font=f, fill=255)
    off, bw, px = len(data), (w + 7) // 8, im.load()
    for y in range(H):
        for bx in range(bw):
            b = 0
            for k in range(8):
                x = bx * 8 + k
                if x < w and px[x, y] >= 128: b |= 0x80 >> k
            data.append(b)
    glyphs.append((c, w, adv, l, off))
out = ['// Oven clock digits: Inter Display Light (SIL Open Font License, see Inter-LICENSE.txt),',
       f'// {size}px, 1-bit, rows packed MSB first. Generated by oven-clock/tools/make-clock-font.py.',
       '#pragma once', '#include <cstdint>', '', 'namespace papyrix::clock_faces::clock_font {', '',
       f'inline constexpr int HEIGHT = {H};',
       'struct Glyph { char c; uint16_t width; uint16_t advance; int16_t xoff; uint32_t offset; };',
       'inline constexpr Glyph GLYPHS[] = {' + ', '.join(f"{{'{c}', {w}, {a}, {l}, {o}}}" for c, w, a, l, o in glyphs) + '};',
       f'inline constexpr uint8_t BITMAP[{len(data)}] = {{']
for i in range(0, len(data), 24): out.append('  ' + ', '.join(f'0x{b:02x}' for b in data[i:i + 24]) + ',')
out += ['};', '', '}  // namespace papyrix::clock_faces::clock_font', '']
open(outpath, 'w').write('\n'.join(out)); print('bytes', len(data))
if len(sys.argv) > 3:
    txt = '11:25'; W = sum(round(f.getlength(ch)) for ch in txt)
    im = Image.new('1', (800, 480), 0)
    ImageDraw.Draw(im).text(((800 - W) // 2, (480 - H) // 2 - top), txt, font=f, fill=1)
    im.save(sys.argv[3])
